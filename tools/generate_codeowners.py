#!/usr/bin/env python3
"""Generate .github/CODEOWNERS from the `owner` field of every KB file.

  generate_codeowners.py          write .github/CODEOWNERS
  generate_codeowners.py --check  exit 1 if CODEOWNERS is out of date

Do not edit CODEOWNERS by hand. Fixed entries for files without frontmatter
(README, AGENTS, CONTRIBUTING, templates, tools) go in .github/CODEOWNERS.base.
"""
import os
import sys

import yaml

from kblib import HANDLE_RE, ROOT, content_files, frontmatter, read

OUT = os.path.join(ROOT, ".github", "CODEOWNERS")
BASE = os.path.join(ROOT, ".github", "CODEOWNERS.base")
HEADER = ("# GENERATED by tools/generate_codeowners.py - do not edit.\n"
          "# Ownership comes from the `owner` field in each file's frontmatter.\n\n")


def build():
    lines = [HEADER]
    if os.path.isfile(BASE):
        with open(BASE, encoding="utf-8") as f:
            lines.append(f.read().rstrip("\n") + "\n\n")
    for path in content_files():
        try:
            fm, _ = frontmatter(read(path))
        except yaml.YAMLError:
            continue  # reported by check_frontmatter.py
        owner = (fm or {}).get("owner")
        if isinstance(owner, str) and HANDLE_RE.match(owner):
            p = "/" + path.replace(os.sep, "/").replace(" ", "\\ ")
            lines.append(f"{p} @{owner.lstrip('@')}\n")
    return "".join(lines)


def main():
    new = build()
    old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
    if "--check" in sys.argv:
        if new != old:
            print("CODEOWNERS is out of date. "
                  "Run tools/generate_codeowners.py.", file=sys.stderr)
            sys.exit(1)
        print("OK")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(new)
    print(f"Wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
