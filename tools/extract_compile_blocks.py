#!/usr/bin/env python3
"""Extract code blocks so CI can build them with ApolloCrossDev (see
tools/compile-snippets.sh).

- build/snippets/: every block marked `kb:compile`. A block is compiled when
  its first line is `; kb:compile` (assembly) or `// kb:compile` (C, C++).
- build/fragments/: every other `asm` block, assembled to check that each
  instruction exists and its operands are legal. Undefined labels are fine
  (vasm imports them). Skipped: blocks whose first line is
  `; kb:no-assemble`, and files generated by document intake.

Output names: <file-path-with-dashes>-<n>.<ext>"""
import os
import re
import shutil

from kblib import ROOT, content_files, frontmatter, read

BLOCK_RE = re.compile(r"^```(\w+)\n(.*?)^```", re.DOTALL | re.MULTILINE)
EXT = {"c": "c", "cpp": "cpp", "asm": "s"}
OUT = os.path.join(ROOT, "build", "snippets")
FRAGMENTS = os.path.join(ROOT, "build", "fragments")


def write(folder, name, code):
    with open(os.path.join(folder, name), "w", encoding="utf-8") as f:
        f.write(code)


def main():
    for d in (OUT, FRAGMENTS):
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
    count = fragments = 0
    for path in content_files():
        text = read(path)
        data, _ = frontmatter(text)
        generated = bool(data and data.get("generated_from"))
        base = path[:-3].replace(os.sep, "-")
        n = f = 0
        for lang, code in BLOCK_RE.findall(text):
            first = code.lstrip().split("\n", 1)[0].strip()
            if first in ("; kb:compile", "// kb:compile"):
                if lang not in EXT:
                    print(f"::warning file={path}::kb:compile on unsupported "
                          f"language '{lang}', skipped")
                    continue
                n += 1
                write(OUT, f"{base}-{n}.{EXT[lang]}", code)
            elif (lang == "asm" and not generated
                  and not first.startswith("; kb:no-assemble")):
                f += 1
                write(FRAGMENTS, f"{base}-{f}.s", code)
        count += n
        fragments += f
    print(f"Extracted {count} snippet(s) to build/snippets/ and "
          f"{fragments} assembly fragment(s) to build/fragments/")


if __name__ == "__main__":
    main()
